const STORAGE_KEY = 'aether_user_language';

export const getSavedLanguage = (): SupportedLanguage => {
  if (typeof window === 'undefined') return 'en';
  try {
    const saved = localStorage.getItem(STORAGE_KEY) as SupportedLanguage;
    if (saved && TRANSLATIONS[saved]) {
      return saved;
    }
  } catch {}
  return 'en';
};

export const setSavedLanguage = (lang: SupportedLanguage): void => {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
    window.dispatchEvent(new CustomEvent('aether_language_change', { detail: { lang } }));
  } catch {}
};

export const getTranslation = (key: string, lang?: SupportedLanguage): string => {
  const currentLang = lang || getSavedLanguage();
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || key;
};
